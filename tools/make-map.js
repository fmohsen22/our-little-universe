// Generates src/map-data.js, the outlines for the kingdom map, from Natural Earth data (public domain)
// as packaged in world-atlas. Only needed to redraw the map:
//   npm install world-atlas@2.0.2 topojson-client@3.1.0   (anywhere)
//   node tools/make-map.js /path/to/node_modules
const fs = require('fs'), path = require('path'), mods = process.argv[2] || path.join(__dirname, '..', 'node_modules');
const topo = require(path.join(mods, 'world-atlas', 'countries-50m.json')), { feature } = require(path.join(mods, 'topojson-client'));

// Fereydun's division of the world among his three sons, as the Shahnameh tells it, laid onto today's countries.
// Iraj: Iran, the heart of the world. Tur: Turan and China, to the north-east and east. Salm: Rum, the West.
// The poem draws no modern borders, so the country lists are our approximation. Everything else is neutral land.
const KINGDOMS = {
  iran: ['Iran', 'Iraq', 'Afghanistan', 'Turkmenistan', 'Azerbaijan', 'Armenia', 'Pakistan', 'Kuwait', 'Bahrain'],
  turan: ['Uzbekistan', 'Tajikistan', 'Kyrgyzstan', 'Kazakhstan', 'Mongolia', 'China', 'Taiwan'],
  rum: ['United Kingdom', 'Portugal', 'Spain', 'France', 'Belgium', 'Netherlands', 'Luxembourg', 'Germany', 'Switzerland', 'Austria', 'Italy', 'San Marino', 'Vatican', 'Malta',
    'Denmark', 'Norway', 'Sweden', 'Finland', 'Estonia', 'Latvia', 'Lithuania', 'Poland', 'Czechia', 'Slovakia', 'Hungary', 'Slovenia', 'Croatia', 'Bosnia and Herz.', 'Serbia', 'Montenegro',
    'Kosovo', 'Albania', 'Macedonia', 'North Macedonia', 'Greece', 'Bulgaria', 'Romania', 'Moldova', 'Ukraine', 'Belarus', 'Turkey', 'Cyprus', 'N. Cyprus', 'Georgia',
    'Syria', 'Lebanon', 'Israel', 'Palestine', 'Jordan', 'Egypt']
};
const kingdomOf = n => Object.keys(KINGDOMS).find(k => KINGDOMS[k].includes(n)) || 'land';

// Equirectangular, stretched for latitude 40 so shapes look right in this band of the world.
const LON0 = -11, LON1 = 136, LAT0 = 4, LAT1 = 67, W = 800, K = W / ((LON1 - LON0) * Math.cos(40 * Math.PI / 180)), H = Math.round((LAT1 - LAT0) * K);
const H2 = 448;
const X = lon => ((lon < -100 ? lon + 360 : lon) - LON0) * K * Math.cos(40 * Math.PI / 180), Y = lat => (LAT1 - lat) * K;   // Russia's far east crosses the date line
// Points closer than 2.4px are dropped, small islands are left out, and everything far outside the frame is skipped.
const r1 = v => Math.round(v * 2) / 2;
function ring(r) {
  let minx = 1e9, maxx = -1e9, miny = 1e9, maxy = -1e9;
  r.forEach(([lon, lat]) => { const x = X(lon), y = Y(lat); minx = Math.min(minx, x); maxx = Math.max(maxx, x); miny = Math.min(miny, y); maxy = Math.max(maxy, y); });
  if (maxx < -20 || minx > W + 20 || maxy < -20 || miny > H + 20) return '';
  if ((maxx - minx) * (maxy - miny) < 5) return '';
  let d = '', last = null;
  r.forEach(([lon, lat]) => { const x = X(lon), y = Y(lat); /* shapes may run past the frame; the drawing clips them */ if (last && Math.hypot(x - last[0], y - last[1]) < 2.4) return; d += (d ? 'L' : 'M') + r1(x) + ' ' + r1(y); last = [x, y]; });
  return d.length > 30 ? d + 'Z' : '';
}
function inView(f) { let hit = false; const scan = a => { if (typeof a[0] === 'number') { if (a[0] > LON0 - 5 && a[0] < LON1 + 5 && a[1] > LAT0 - 5 && a[1] < LAT1 + 5) hit = true; } else a.forEach(scan); }; scan(f.geometry.coordinates); return hit; }
function shape(f) { const g = f.geometry, polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates; return polys.map(p => p.map(ring).join('')).join(''); }
const out = { land: '', iran: '', turan: '', rum: '' };
feature(topo, topo.objects.countries).features.filter(f => f.geometry && inView(f)).forEach(f => {
  const n = f.properties.name, d = shape(f);
  out[kingdomOf(n)] += d;
});
// The Oxus (Amu Darya), the border between Iran and Turan in the Shahnameh: from the Pamirs to the Aral Sea.
const oxus = [[73.6, 37.1], [71.6, 37.4], [70.6, 38.4], [69.4, 37.3], [68.3, 37.1], [67.3, 37.2], [66.4, 37.4], [65.3, 38.2], [64.2, 38.9], [63.3, 39.6], [62.1, 40.3], [61.2, 41.2], [60.4, 42.3], [59.9, 43.4]];
out.oxus = oxus.map(([lon, lat], i) => (i ? 'L' : 'M') + X(lon).toFixed(1) + ' ' + Y(lat).toFixed(1)).join('');
out.w = W; out.h = H;
out.at = { iran: [X(56), Y(30.5)], turan: [X(96), Y(39)], rum: [X(17), Y(47.5)], oxus: [X(64.6), Y(40.6)], uk: [X(-2.5), Y(53.8)], persia: [X(53), Y(32.5)] };
const file = path.join(__dirname, '..', 'src', 'map-data.js');
fs.writeFileSync(file, '/* Generated by tools/make-map.js from Natural Earth (public domain) via world-atlas. Do not edit by hand. */\nwindow.WPM_MAP_DATA = ' + JSON.stringify(out) + ';\n');
console.log('wrote', file, Math.round(fs.statSync(file).size / 1024) + ' KB', W + 'x' + H);
